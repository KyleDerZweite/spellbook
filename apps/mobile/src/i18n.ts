export type Message = keyof typeof en;
export type Translate = (message: Message) => string;
export const messages = { en, de };

export function errorMessage(t: Translate, error: unknown) {
	if (error instanceof NetworkError) return t('networkError');
	if (error instanceof HttpError) {
		if (error.kind === 'DEMO_ACCOUNT_READ_ONLY') return t('demoReadOnly');
		if (error.status === 409) return t('conflict');
		return `${t('serverError')} (${error.status}).`;
	}
	return t('error');
}
